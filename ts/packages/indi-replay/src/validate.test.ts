import { describe, expect, it } from 'vitest'
import { formatG } from './validate.js'

describe('formatG', () => {
  it.each([
    [1000, '1000'],
    [1e6, '1e+06'],
    [100000, '100000'],
    [12345678, '1.23457e+07'],
    [-1, '-1'],
    [0.5, '0.5'],
    [1e-5, '1e-05'],
    [0.0001, '0.0001'],
    [3.4028234663852886e38, '3.40282e+38'],
    [-3.4028234663852886e38, '-3.40282e+38'],
    [999999.5, '1e+06'],
    [123456, '123456'],
    [1234567, '1.23457e+06'],
    [0.000123456789, '0.000123457'],
    [300.5, '300.5'],
    [99999999, '1e+08'],
    [0.010000000000000000208, '0.01'],
    [0, '0'],
  ])('writes %s as C\'s %%g does: %s', (value, written) => {
    expect(formatG(value)).toBe(written)
  })
})
